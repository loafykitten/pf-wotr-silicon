"""Generate flat_gen.cpp: Steamworks SDK 1.41's flat C API, implemented as thin calls into
the C++ interfaces, exactly like Valve's own 1.41 libsteam_api did.

Steamworks.NET 11.0.0 (built into the game) P/Invokes these flat functions with interface
pointers it obtained for 1.41 interface versions (SteamUser019, ...). Valve's current
libsteam_api has different flat functions compiled against newer interface layouts, so
these wrappers must be compiled against the 1.41 headers.

usage: python3 -I gen_flat.py <sdk-1.41/steam dir> <out.cpp>
"""
import json
import re
import sys

STEAM_ID = {"class CSteamID", "CSteamID"}
GAME_ID = {"class CGameID", "CGameID"}


def main(sdk, out):
    methods = json.load(open(f"{sdk}/steam_api.json"))["methods"]
    flat = [l.strip() for l in open(f"{sdk}/steam_api_flat.h") if l.startswith("S_API")]
    if len(methods) != len(flat):
        raise SystemExit(f"steam_api.json has {len(methods)} methods, steam_api_flat.h {len(flat)}")

    lines = [
        "// Generated by gen_flat.py from the Steamworks SDK 1.41 headers. Do not edit.",
        '#include "steam/steam_api.h"',
        '#include "steam/steam_gameserver.h"',
        "// steam_api_flat.h isn't included: it redefines lint64/ulint64 differently from",
        "// steamtypes.h (both 64-bit, same ABI). Signatures are copied from it verbatim.",
        "// The 1.41 S_API macro tests `GNUC` (not __GNUC__), so it never adds default",
        "// visibility; export explicitly.",
        '#define SHIM_EXPORT extern "C" __attribute__((visibility("default")))',
        "",
    ]
    for m, decl in zip(methods, flat):
        sig = re.fullmatch(r"S_API (.+?) ?(SteamAPI_\w+)\((.*)\);", decl)
        if not sig:
            raise SystemExit(f"can't parse: {decl}")
        ret, name, params = sig.group(1).strip(), sig.group(2), sig.group(3)
        # Overloads get a numeric suffix in the flat name (GetStat0); the C++ call
        # resolves by argument types.
        if not re.fullmatch(rf"SteamAPI_{m['classname']}_{m['methodname']}\d*", name):
            raise SystemExit(f"json/flat order mismatch: {m['classname']}::{m['methodname']} vs {name}")
        if not params.startswith("intptr_t instancePtr"):
            raise SystemExit(f"no instance pointer: {decl}")
        args = ", ".join(p["paramname"] for p in m.get("params", []))
        call = f"(({m['classname']} *)instancePtr)->{m['methodname']}({args})"
        if m["methodname"] == f"Destruct{m['classname']}":
            # The flat API exposes the interface's virtual destructor under this name.
            call = f"(({m['classname']} *)instancePtr)->~{m['classname']}()"
        jret = m["returntype"].strip()
        if ret == "void":
            body = f"{call};"
        elif jret in STEAM_ID and ret == "uint64":
            body = f"return {call}.ConvertToUint64();"
        elif jret in GAME_ID and ret == "uint64":
            body = f"return {call}.ToUint64();"
        else:
            body = f"return {call};"
        lines.append(f"SHIM_EXPORT {ret} {name}({params}) {{ {body} }}")
    # Imported by Steamworks.NET 11 but missing from Valve's 1.41 flat API (its generator
    # skipped this const char ** method), so add it by hand.
    lines.append("SHIM_EXPORT void SteamAPI_ISteamHTMLSurface_FileLoadDialogResponse(intptr_t instancePtr, "
                 "HHTMLBrowser unBrowserHandle, const char **pchSelectedFiles) { "
                 "((ISteamHTMLSurface *)instancePtr)->FileLoadDialogResponse(unBrowserHandle, pchSelectedFiles); }")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"generated {len(methods)} flat functions into {out}")


if __name__ == "__main__":
    main(*sys.argv[1:])
